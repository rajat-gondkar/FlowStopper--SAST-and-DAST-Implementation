#!/usr/bin/env bash
# Regenerate requirements.lock (runtime) and requirements-dev.lock (runtime + dev) from pyproject.toml.
# Uses throw-away venvs so the pins reflect a clean resolution. Commit both files afterwards.
set -euo pipefail
cd "$(dirname "$0")/.."
PY="${PYTHON:-python3.12}"
TMP=".venv-lock"

freeze() {  # $1 = pip install target, $2 = output file
  rm -rf "$TMP"
  "$PY" -m venv "$TMP"
  "$TMP/bin/python" -m pip install --quiet --upgrade pip
  "$TMP/bin/python" -m pip install --quiet "$1"
  {
    echo "# Generated by scripts/lock.sh on $("$TMP/bin/python" -c 'import platform; print(platform.python_version())') - do not edit by hand."
    "$TMP/bin/python" -m pip freeze --exclude-editable | grep -iv '^flowstopper' | sort -f
  } > "$2"
  echo "wrote $2"
}

freeze "." requirements.lock
freeze ".[dev]" requirements-dev.lock
rm -rf "$TMP" build ./*.egg-info
